"""DWA variant whose command window and rollout agree about acceleration.

Written to solve the open-water "ego is overtaken" problem: ``owenc_overtaken_ego``
and ``owenc_overtaken_ego_fast`` were the only two of the 11 open-water encounter
cases that did not reach the goal. Everything this module does follows from that
one goal. Full record: ``results/v20.7.9_ramped_window/README.md``.

The classic dynamic window admits only the velocities reachable in ONE ``dt``
and then scores each of them by holding that velocity for the whole
``predict_time_obstacle``. At a 30 s horizon those two statements contradict
each other: from rest the window offers v <= 0.02 m/s, so the planner predicts
itself travelling 0.6 units in 30 s when it can really cover 14.4. A target
closing from astern then appears to sweep through every candidate, every cost
becomes inf, and the planner aborts on iteration 0 with "No best trajectory
found".

This module makes the two agree by reading three config knobs:

``v_window_ramp_time``
    Seconds of acceleration authority used to size the v window, so a sampled v
    means "the speed I am aiming for" rather than "the speed I will have next
    step". Set it to ``max_speed / max_accel`` to expose the full speed range.
``ramped_rollout``
    Integrate a sampled (v, omega) as a setpoint approached at ``max_accel`` /
    ``max_delta_yaw_rate``, in the rollout AND in execution, instead of applying
    it instantly. Widening the window without this would let the simulated ego
    jump 0 -> 0.5 m/s in one dt and silently violate max_accel.
``all_candidates_collide_fallback``
    ``"least_bad"`` keeps the candidate with the largest minimum clearance when
    every ADMISSIBLE candidate scores inf, instead of raising. That is Guard B
    ("No best trajectory found"). It does not and never did catch Guard A
    ("No admissible (v, omega) pairs"), which is what the former name
    ``no_admissible_fallback`` wrongly implied; the old key still loads.

The search stays a 2-D grid over (v, omega): one setpoint per candidate, with
the acceleration profile generated by the rollout. Cost grows linearly with the
number of samples, not exponentially -- that only happens if you search
*sequences* of commands.

Known limitations of the prototype:
  * The yaw window is left at one dt. Unlike v, a yaw rate IS reachable within
    one dt (max_delta_yaw_rate * dt equals the whole window), so it is already
    self-consistent; widening it toward horizon-reachable rates is the same
    change and has not been made here.
  * ``closest_obstacle_on_curve`` (admissibility + static cost) still assumes a
    constant-velocity arc, so it under-estimates travel during the ramp.
"""

